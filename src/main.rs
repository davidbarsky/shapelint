/// A syntax-only design linter for Rust, TOML, and Buck/Bazel files, meant to run as a hook.
///
/// With no subcommand, `shapelint [PATHS]` is `shapelint check [PATHS]`.
#[derive(Parser)]
#[command(name = "shapelint", version, styles = STYLES, after_long_help = COMPLETIONS_HELP)]
struct Cli {
    #[command(subcommand)]
    command: Option<Commands>,

    #[command(flatten)]
    selection: SelectionArgs,

    /// Lint files changed by a jj revision; @ reports only changed lines.
    #[arg(short = 'r', long, global = true, value_name = "REVSET")]
    revision: Option<String>,

    /// Exclude a directory and its contents (repeatable; relative to the working directory).
    #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
    exclude: Vec<PathBuf>,

    #[command(flatten)]
    report: ReportArgs,

    /// When to use color in diagnostics, help, and errors.
    #[arg(long, global = true, value_enum, default_value_t = ColorChoice::Auto, value_name = "WHEN")]
    color: ColorChoice,
}

#[derive(Subcommand)]
enum Commands {
    /// Lint files or directories (the default).
    Check {
        #[command(flatten)]
        selection: SelectionArgs,
        /// Exclude a directory and its contents (repeatable; relative to the working directory).
        #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
        exclude: Vec<PathBuf>,
    },
    /// Lint changed lines in jj @, or files selected by another revision.
    Changed {
        /// Exclude a directory and its contents (repeatable; relative to the working directory).
        #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
        exclude: Vec<PathBuf>,
    },
    /// Run as a hook, reading the hook's JSON event on stdin.
    Hook {
        /// Which tool is calling.
        #[arg(value_enum)]
        target: HookTarget,
        /// Exclude a directory and its contents (repeatable; relative to the working directory).
        #[arg(long, value_name = "DIR", value_hint = ValueHint::DirPath)]
        exclude: Vec<PathBuf>,
    },
    /// List the rules, or describe one.
    Rules {
        /// A rule to describe.
        #[arg(value_parser = rule_names())]
        rule: Option<String>,
    },
}

#[derive(Args)]
struct SelectionArgs {
    /// Files or directories to lint [default: .]
    #[arg(conflicts_with = "revision", value_hint = ValueHint::AnyPath, add = ArgValueCompleter::new(PathCompleter::any().filter(|path| match Language::of(&path.to_string_lossy()) {
        Some(_) => true,
        None => path.is_dir(),
    })))]
    paths: Vec<PathBuf>,
}

/// Reporting flags. Global, so they work before or after the subcommand.
#[derive(Args)]
struct ReportArgs {
    /// How to print findings.
    #[arg(long, global = true, value_enum, default_value_t = Format::Text)]
    format: Format,
    /// Attach the enclosing item's text to each finding.
    #[arg(long, global = true)]
    with_source: bool, // shapelint: allow(boolean-state) -- clap represents this external flag as a bool.
    /// Report only rules in this set.
    #[arg(long, global = true, value_enum)]
    only: Option<RuleSetArg>,
    /// Exit 1 for findings from this rule set [default: any finding]
    #[arg(long, global = true, value_enum)]
    fail_on: Option<RuleSetArg>,
    /// Always exit 0, even with findings.
    #[arg(long, global = true)]
    exit_zero: bool, // shapelint: allow(boolean-state) -- clap represents this external flag as a bool.
}

#[derive(Clone, Copy, ValueEnum)]
enum Format {
    /// Annotated source snippets.
    Text,
    /// One line per finding.
    Short,
    /// One JSON object per finding, per line.
    Json,
}

#[derive(Clone, Copy, ValueEnum)]
enum RuleSetArg {
    /// The project policies selected by the commit hooks.
    Mechanical,
    /// All ordinary lints, including the mechanical policies.
    Lint,
}

impl From<RuleSetArg> for RuleSet {
    fn from(set: RuleSetArg) -> Self {
        match set {
            RuleSetArg::Mechanical => RuleSet::Mechanical,
            RuleSetArg::Lint => RuleSet::Lints,
        }
    }
}

#[derive(Clone, Copy, ValueEnum)]
enum HookTarget {
    /// Claude Code PostToolUse: exit 2 shows the findings to Claude.
    Claude,
}

/// Rule names, validated and completed with their summaries.
fn rule_names() -> PossibleValuesParser {
    PossibleValuesParser::new(
        RULES
            .iter()
            .map(|r| PossibleValue::new(r.id).help(r.summary)),
    )
}

#[derive(Debug, thiserror::Error)]
enum CliError {
    #[error("could not resolve {path}: {source}")]
    Resolve {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("revision selection requires a jj repository")]
    NoJjRepository,
    #[error("could not run jj: {0}")]
    JjRun(#[source] std::io::Error),
    #[error("could not list changed files: {0}")]
    JjDiff(String),
    #[error("could not parse changed paths from jj: {0}")]
    JjPaths(#[from] serde_json::Error),
    #[error("could not parse jj diff hunk: {0}")]
    JjHunk(String),
    #[error("--revision is only supported when linting files")]
    RevisionCommand,
    #[error("--revision cannot be combined with explicit paths")]
    RevisionPaths,
    #[error("{0}: no such file or directory")]
    Missing(PathBuf),
    #[error("could not read {path}: {source}")]
    Read {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("could not inspect {path}: {source}")]
    Metadata {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("could not list {path}: {source}")]
    Directory {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error(transparent)]
    Lint(#[from] LintError),
}

/// `--color` decides clap's own help and error colors too, so read it before clap parses.
fn color_from_args() -> ColorChoice {
    let parse = |v: &str| match ColorChoice::from_str(v, true) {
        Ok(color) => color,
        Err(_) => ColorChoice::Auto,
    };
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        if arg == "--" {
            break;
        }
        if let Some(value) = arg.strip_prefix("--color=") {
            return parse(value);
        }
        if arg == "--color" {
            return args.next().map_or(ColorChoice::Auto, |v| parse(&v));
        }
    }
    ColorChoice::Auto
}

fn command() -> clap::Command {
    Cli::command().color(color_from_args())
}

fn main() -> ExitCode {
    // Answers shell completion requests (`COMPLETE=<shell>`) and exits; otherwise returns.
    CompleteEnv::with_factory(command).complete();
    let cli = match Cli::from_arg_matches(&command().get_matches()) {
        Ok(cli) => cli,
        Err(e) => e.exit(),
    };
    match run(cli) {
        Ok(code) => code,
        Err(e) => {
            eprintln!("shapelint: {e}");
            ExitCode::from(64)
        }
    }
}

fn run(cli: Cli) -> Result<ExitCode, CliError> {
    let cwd = absolute_path(Path::new("."))?;
    let revision = match (&cli.command, cli.revision) {
        (Some(Commands::Changed { exclude: _ }), None) => Some("@".to_owned()),
        (_, revision) => revision,
    };
    let color = cli.color;
    let args = cli.report;
    let mut exclude = cli.exclude;
    // Clap's global Append arguments replace parent values at subcommands.
    // Keep both scopes so exclusions on either side of the subcommand add up.
    match &cli.command {
        Some(
            Commands::Check {
                selection: _,
                exclude: local,
            }
            | Commands::Changed { exclude: local }
            | Commands::Hook {
                target: _,
                exclude: local,
            },
        ) => exclude.extend(local.iter().cloned()),
        Some(Commands::Rules { rule: _ }) | None => {}
    }
    let source = match args.with_source {
        true => SourceMode::Include,
        false => SourceMode::Omit,
    };
    let load = || load_config(&cwd, args.only.map(RuleSet::from), source, &exclude);
    let (files, config) = match cli.command {
        Some(
            Commands::Rules { rule: _ }
            | Commands::Hook {
                target: _,
                exclude: _,
            },
        ) if let Some(_) = revision => {
            return Err(CliError::RevisionCommand);
        }
        Some(Commands::Rules { rule }) => {
            return Ok(list_rules(
                rule.as_deref(),
                args.only.map(RuleSet::from),
                color,
            ));
        }
        Some(Commands::Hook {
            target: HookTarget::Claude,
            exclude: _,
        }) => return hook_claude(args.only.map(RuleSet::from), &exclude),
        Some(Commands::Changed { exclude: _ }) => {
            let config = load()?;
            let revision = match revision.as_deref() {
                Some(revision) => revision,
                None => "@",
            };
            let files = changed_files(&cwd, revision, &config.exclude)?;
            (files, config)
        }
        Some(Commands::Check {
            selection,
            exclude: _,
        }) => {
            let config = load()?;
            (
                selection.files(&cwd, revision.as_deref(), &config.exclude)?,
                config,
            )
        }
        None => {
            let config = load()?;
            (
                cli.selection
                    .files(&cwd, revision.as_deref(), &config.exclude)?,
                config,
            )
        }
    };
    let mut results = lint_paths(&files, &config)?;
    if let Some("@") = revision.as_deref() {
        diff::retain_changed_lines(&mut results)?;
    }
    Ok(report(&args, color, results))
}

impl SelectionArgs {
    fn files(
        self,
        cwd: &Path,
        revision: Option<&str>,
        exclude: &[PathBuf],
    ) -> Result<Vec<PathBuf>, CliError> {
        let Self { paths } = self;
        match (revision, paths.as_slice()) {
            (Some(revision), []) => changed_files(cwd, revision, exclude),
            (None, paths) => expand(paths, exclude),
            (Some(_), [_, ..]) => Err(CliError::RevisionPaths),
        }
    }
}

#[derive(Clone, Copy)]
enum Terminal {
    Interactive,
    NonInteractive,
}

fn terminal() -> Terminal {
    match std::io::stdout().is_terminal() {
        true => Terminal::Interactive,
        false => Terminal::NonInteractive,
    }
}

/// Diagnostic color: `--color` first, then `NO_COLOR`/`CLICOLOR_FORCE`, then whether `stream` is a terminal.
fn diagnostic_style(color: ColorChoice, terminal: Terminal) -> Style {
    let set = |var: &str| match std::env::var_os(var) {
        Some(value) => !value.is_empty(),
        None => false,
    };
    match (color, terminal) {
        (ColorChoice::Always, _) => Style::Ansi,
        (ColorChoice::Never, _) => Style::Plain,
        (ColorChoice::Auto, _) if set("NO_COLOR") => Style::Plain,
        (ColorChoice::Auto, _) if set("CLICOLOR_FORCE") => Style::Ansi,
        (ColorChoice::Auto, Terminal::Interactive) => Style::Ansi,
        (ColorChoice::Auto, Terminal::NonInteractive) => Style::Plain,
    }
}

fn list_rules(rule: Option<&str>, only: Option<RuleSet>, color: ColorChoice) -> ExitCode {
    let ansi = diagnostic_style(color, terminal()) == Style::Ansi;
    let paint = |style: styling::Style, text: &str| {
        if ansi {
            format!("{style}{text}{style:#}")
        } else {
            text.to_string()
        }
    };
    let id_style = AnsiColor::Cyan.on_default().effects(Effects::BOLD);
    let kind_style = |kind: Kind| match kind {
        Kind::Lint => AnsiColor::Yellow.on_default(),
        Kind::AnalysisGap => AnsiColor::Cyan.on_default(),
    };
    let mut out = std::io::stdout().lock();
    let rules = RULES.iter().filter(|r| match rule {
        Some(name) => name == r.id,
        None => true,
    });
    for r in rules {
        if let Some(set) = only
            && let None = set.select(r)
        {
            continue;
        }
        let kind = format!("{:<6}", r.kind().label());
        let _ = match rule {
            None => writeln!(
                out,
                "{}  {}  {}",
                paint(id_style, &format!("{:<20}", r.id)),
                paint(kind_style(r.kind()), &kind),
                r.summary
            ),
            Some(_) => writeln!(
                out,
                "{} ({})\n\n{}\n\nSuppress one site with `// shapelint: allow({})` on the item or the line above it.",
                paint(id_style, r.id),
                paint(kind_style(r.kind()), r.kind().label()),
                r.summary,
                r.id
            ),
        };
    }
    ExitCode::SUCCESS
}

/// Finds `.shapelint` in `start` or an ancestor, parses it, and prints its warnings.
fn load_config(
    start: &Path,
    only: Option<RuleSet>,
    source: SourceMode,
    exclude: &[PathBuf],
) -> Result<Config, CliError> {
    let found = start
        .ancestors()
        .map(|d| d.join(".shapelint"))
        .find(|p| p.is_file());
    let mut config = match found.as_ref().map(|p| (p, std::fs::read_to_string(p))) {
        Some((path, Ok(text))) => {
            let shapelint::ConfigParse { config, warnings } = Config::parse(&text);
            for w in warnings {
                eprintln!("shapelint: {}:{}: {}", path.display(), w.line, w.message);
            }
            config
        }
        Some((path, Err(e))) => {
            eprintln!(
                "shapelint: could not read {}: {e}; using defaults",
                path.display()
            );
            Config::default()
        }
        None => Config::default(),
    };
    config.only = only;
    config.with_source = source;
    let base = match found.as_deref().and_then(Path::parent) {
        Some(base) => base,
        None => start,
    };
    config.exclude = config
        .exclude
        .iter()
        .map(|path| absolute_path(&base.join(path)))
        .collect::<Result<_, _>>()?;
    for path in exclude {
        config.exclude.push(absolute_path(path)?);
    }
    Ok(config)
}

// Match literal path components without requiring excluded directories to exist.
// Symlinks are not resolved: exclusions describe paths used to reach a file.
fn absolute_path(path: &Path) -> Result<PathBuf, CliError> {
    let absolute = std::path::absolute(path).map_err(|source| CliError::Resolve {
        path: path.to_path_buf(),
        source,
    })?;
    let mut normalized = PathBuf::new();
    for component in absolute.components() {
        match component {
            Component::ParentDir => {
                normalized.pop();
            }
            Component::CurDir => {}
            Component::Prefix(_) | Component::RootDir | Component::Normal(_) => {
                normalized.push(component)
            }
        }
    }
    Ok(normalized)
}

fn excluded<'a>(path: &Path, exclude: &'a [PathBuf]) -> Result<Option<&'a PathBuf>, CliError> {
    let path = absolute_path(path)?;
    Ok(exclude.iter().find(|directory| path.starts_with(directory)))
}

/// Lintable files under each path, in sorted order; `.` when no paths are given.
fn expand(paths: &[PathBuf], exclude: &[PathBuf]) -> Result<Vec<PathBuf>, CliError> {
    let roots: Vec<PathBuf> = if paths.is_empty() {
        vec![PathBuf::from(".")]
    } else {
        paths.to_vec()
    };
    let mut files = Vec::new();
    let mut seen = rustc_hash::FxHashSet::default();
    for root in roots {
        if let Some(_) = excluded(&root, exclude)? {
            continue;
        }
        if !root.exists() {
            return Err(CliError::Missing(root));
        }
        collect(&root, exclude, &mut files)?;
    }
    let mut unique = Vec::new();
    for path in files {
        if seen.insert(absolute_path(&path)?) {
            unique.push(path);
        }
    }
    Ok(unique)
}

fn collect(path: &Path, exclude: &[PathBuf], out: &mut Vec<PathBuf>) -> Result<(), CliError> {
    // An explicit stack: directory depth is user-controlled.
    let mut stack = vec![path.to_path_buf()];
    while let Some(path) = stack.pop() {
        if let Some(_) = excluded(&path, exclude)? {
            continue;
        }
        let metadata = std::fs::symlink_metadata(&path).map_err(|source| CliError::Metadata {
            path: path.clone(),
            source,
        })?;
        let metadata = if metadata.is_symlink() {
            let target = std::fs::metadata(&path).map_err(|source| CliError::Metadata {
                path: path.clone(),
                source,
            })?;
            if target.is_dir() {
                continue;
            }
            target
        } else {
            metadata
        };
        if metadata.is_dir() {
            if let Some(name) = path.file_name()
                && ["target", ".git", ".jj", "node_modules", "buck-out"]
                    .contains(&name.to_string_lossy().as_ref())
            {
                continue;
            }
            let entries = std::fs::read_dir(&path).map_err(|source| CliError::Directory {
                path: path.clone(),
                source,
            })?;
            let mut entries: Vec<PathBuf> = entries
                .map(|entry| entry.map(|entry| entry.path()))
                .collect::<Result<_, _>>()
                .map_err(|source| CliError::Directory { path, source })?;
            entries.sort();
            stack.extend(entries.into_iter().rev());
        } else if metadata.is_file()
            && let Some(_) = Language::of(&path.to_string_lossy())
        {
            out.push(path);
        }
    }
    Ok(())
}

struct LintedSource {
    input: SourceInput,
    findings: Vec<Finding>,
}

/// All supplied files participate in implementation counts, including test implementations.
fn lint_paths(files: &[PathBuf], config: &Config) -> Result<Vec<LintedSource>, CliError> {
    let mut inputs = Vec::with_capacity(files.len());
    for path in files {
        let text = std::fs::read_to_string(path).map_err(|source| CliError::Read {
            path: path.clone(),
            source,
        })?;
        inputs.push(SourceInput::try_new(
            std::fs::canonicalize(path)
                .map_err(|source| CliError::Resolve {
                    path: path.clone(),
                    source,
                })?
                .to_string_lossy(),
            text,
        )?);
    }
    let findings = shapelint::lint_sources(&inputs, config)?;
    Ok(files
        .iter()
        .zip(inputs)
        .zip(findings)
        .map(|((path, mut input), mut findings)| {
            input.name = path.to_string_lossy().trim_start_matches("./").into();
            for finding in &mut findings {
                finding.path = input.name.to_string();
            }
            LintedSource { input, findings }
        })
        .collect())
}

fn report(args: &ReportArgs, color: ColorChoice, results: Vec<LintedSource>) -> ExitCode {
    let style = diagnostic_style(color, terminal());
    let fail_on = args.fail_on.map(|filter| {
        let set = RuleSet::from(filter);
        RULES
            .iter()
            .filter_map(|rule| set.select(rule))
            .map(|rule| rule.id)
            .collect::<rustc_hash::FxHashSet<_>>()
    });
    let mut out = std::io::stdout().lock();
    let mut failing = false;
    for LintedSource { input, findings } in &results {
        failing |= match &fail_on {
            Some(rules) => findings.iter().any(|finding| rules.contains(finding.rule)),
            None => !findings.is_empty(),
        };
        let _ = match args.format {
            Format::Text if findings.is_empty() => Ok(()),
            Format::Text => write!(out, "{}", shapelint::render(findings, input, style)),
            Format::Short => findings
                .iter()
                .try_for_each(|f| writeln!(out, "{}", short_line(f))),
            Format::Json => findings.iter().try_for_each(|f| {
                writeln!(
                    out,
                    "{}",
                    serde_json::to_string(f).expect("findings serialize")
                )
            }),
        };
    }
    if !failing || args.exit_zero {
        ExitCode::SUCCESS
    } else {
        ExitCode::from(1)
    }
}

fn short_line(f: &Finding) -> String {
    format!(
        "{}:{}:{}: {} [{}] {}: {}",
        f.path,
        f.line,
        f.col,
        f.rule,
        f.kind.label(),
        f.item,
        f.message
    )
}

/// Revisions select paths; their contents are read from the working copy.
fn changed_files(
    cwd: &Path,
    revision: &str,
    exclude: &[PathBuf],
) -> Result<Vec<PathBuf>, CliError> {
    use std::process::Command;
    let root = cwd
        .ancestors()
        .find(|d| d.join(".jj").is_dir())
        .ok_or(CliError::NoJjRepository)?;
    let output = Command::new("jj")
        .args([
            "diff",
            "--color=never",
            "--no-pager",
            "--template",
            "json(path) ++ \"\\n\"",
            "-r",
            revision,
        ])
        .current_dir(cwd)
        .output()
        .map_err(CliError::JjRun)?;
    if !output.status.success() {
        return Err(CliError::JjDiff(
            String::from_utf8_lossy(&output.stderr).trim().to_string(),
        ));
    }
    let paths = serde_json::Deserializer::from_slice(&output.stdout)
        .into_iter::<PathBuf>()
        .collect::<Result<Vec<_>, _>>()?;
    let mut files = Vec::new();
    for path in paths {
        let path = root.join(path);
        match (
            Language::of(&path.to_string_lossy()),
            excluded(&path, exclude)?,
        ) {
            (Some(_), None) => {}
            (None, _) | (_, Some(_)) => continue,
        }
        let metadata = match std::fs::metadata(&path) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
            Err(source) => return Err(CliError::Metadata { path, source }),
        };
        if metadata.is_file() {
            let path = match path.strip_prefix(cwd) {
                Ok(relative) => relative.to_path_buf(),
                Err(_) => path,
            };
            files.push(path);
        }
    }
    Ok(files)
}

/// Claude Code PostToolUse adapter. Exit 2 puts stderr in front of Claude; exit 0 is silent.
/// Findings already reported in this session (same fingerprint) are not repeated. Output is
/// always plain: it goes to a model, not a terminal.
fn hook_claude(only: Option<RuleSet>, exclude: &[PathBuf]) -> Result<ExitCode, CliError> {
    let mut input = String::new();
    match std::io::stdin().read_to_string(&mut input) {
        Ok(_) => {}
        Err(source) => {
            eprintln!("shapelint: could not read hook event: {source}");
            return Ok(ExitCode::SUCCESS);
        }
    }
    let Ok(event) = serde_json::from_str::<serde_json::Value>(&input) else {
        return Ok(ExitCode::SUCCESS);
    };
    let Some(file) = event
        .pointer("/tool_input/file_path")
        .and_then(|v| v.as_str())
    else {
        return Ok(ExitCode::SUCCESS);
    };
    let cwd = event.get("cwd").and_then(|v| v.as_str()).map(PathBuf::from);
    let path = PathBuf::from(file);
    let path = match path.is_absolute() {
        true => path,
        false => match cwd.as_ref() {
            Some(directory) => directory.join(path),
            None => path,
        },
    };
    let Some(_) = Language::of(&path.to_string_lossy()) else {
        return Ok(ExitCode::SUCCESS);
    };
    // `.shapelint` is found from the session's cwd (the project), not the hook process's cwd.
    let config_start = match cwd.as_deref().or(path.parent()) {
        Some(directory) => directory,
        None => Path::new("."),
    };
    let config = load_config(config_start, only, SourceMode::Omit, exclude)?;
    if let Some(_) = excluded(&path, &config.exclude)? {
        return Ok(ExitCode::SUCCESS);
    }
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(source) => {
            eprintln!("shapelint: could not read {}: {source}", path.display());
            return Ok(ExitCode::SUCCESS);
        }
    };
    // A relative name keeps path heuristics (tests/, BUCK) working and output short.
    let shown = match cwd.as_ref() {
        Some(directory) => match path.strip_prefix(directory) {
            Ok(relative) => relative.to_path_buf(),
            Err(_) => path.clone(),
        },
        None => path.clone(),
    };
    let source = match SourceInput::try_new(shown.to_string_lossy(), text) {
        Ok(source) => source,
        Err(e) => {
            eprintln!("shapelint: {e}");
            return Ok(ExitCode::SUCCESS);
        }
    };
    let findings = match shapelint::lint(&source, &config) {
        Ok(findings) => findings,
        Err(e) => {
            eprintln!("shapelint: {e}");
            return Ok(ExitCode::SUCCESS);
        }
    };

    let session = match event.get("session_id").and_then(|v| v.as_str()) {
        Some(session) => session,
        None => "default",
    };
    let state_dir = match std::env::var_os("SHAPELINT_STATE_DIR") {
        Some(path) => PathBuf::from(path),
        None => std::env::temp_dir().join("shapelint"),
    };
    let _ = std::fs::create_dir_all(&state_dir);
    // Fingerprints use the v2 digest contract; keep the old namespace untouched so an
    // upgrade can announce each finding once under the new identity.
    let state = state_dir.join(format!("{}.v2.seen", session.replace(['/', '\\'], "_")));
    let seen = match std::fs::read_to_string(&state) {
        Ok(contents) => contents,
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(source) => {
            eprintln!(
                "shapelint: could not read hook state {}: {source}",
                state.display()
            );
            return Ok(ExitCode::SUCCESS);
        }
    };
    let seen: rustc_hash::FxHashSet<&str> = seen.lines().collect();
    let fresh: Vec<Finding> = findings
        .into_iter()
        .filter(|f| !seen.contains(f.fingerprint.as_str()))
        .collect();
    if fresh.is_empty() {
        return Ok(ExitCode::SUCCESS);
    }
    if let Ok(mut f) = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&state)
    {
        for finding in &fresh {
            let _ = writeln!(f, "{}", finding.fingerprint);
        }
    }
    let mut err = std::io::stderr().lock();
    let _ = writeln!(
        err,
        "shapelint found new lints in {}. Interpret each signal using the source, its callers, and the project's requirements. Make the change when the evidence supports it. When the existing code is appropriate, keep it and explain why.\n",
        shown.display()
    );
    let _ = write!(err, "{}", shapelint::render(&fresh, &source, Style::Plain));
    Ok(ExitCode::from(2))
}
